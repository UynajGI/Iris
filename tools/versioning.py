"""Synchronize Iris-owned version fields without resolving dependencies or publishing."""

import json
import re
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MANIFESTS = ("Cargo.toml", "apps/shell/src-tauri/Cargo.toml", "components/raw-decoder/Cargo.toml")
JSON_FILES = (
    "apps/shell/package.json",
    "apps/shell/package-lock.json",
    "apps/shell/src-tauri/tauri.conf.json",
)
LOCKS = ("Cargo.lock", "apps/shell/src-tauri/Cargo.lock", "components/raw-decoder/Cargo.lock")
OWNED = {"iris-core", "iris-daemon", "iris-cli", "iris-mcp", "iris-shell", "iris-raw-decoder"}
GENERATED = "apps/shell/src/generated/version.ts"


def validate(version):
    number = r"(?:0|[1-9][0-9]*)"
    suffix = r"(?:-(?:[0-9A-Za-z-]+)(?:\.[0-9A-Za-z-]+)*)?"
    if not re.fullmatch(rf"{number}\.{number}\.{number}{suffix}", version):
        raise ValueError("Expected a version such as 0.1.0-beta4 or 1.0.0")
    if "-" in version:
        for part in version.split("-", 1)[1].split("."):
            if part.isdigit() and len(part) > 1 and part.startswith("0"):
                raise ValueError("Numeric prerelease identifiers cannot have leading zeroes")
    return version


def current(root=ROOT):
    return tomllib.loads((root / "Cargo.toml").read_text("utf-8"))["workspace"]["package"][
        "version"
    ]


def generated(version):
    return f'// Generated by tools/sync-version.py; do not edit by hand.\nexport const APP_VERSION = "{version}";\n'


def lock_versions(text):
    return [(p["name"], p["version"]) for p in tomllib.loads(text)["package"] if p["name"] in OWNED]


def check(version, root=ROOT):
    validate(version)
    for name in MANIFESTS:
        document = tomllib.loads((root / name).read_text("utf-8"))
        package = document["workspace"]["package"] if name == "Cargo.toml" else document["package"]
        if package["version"] != version:
            raise ValueError(f"{name}: version differs from {version}")
    for name in JSON_FILES:
        data = json.loads((root / name).read_text("utf-8"))
        if data["version"] != version or (
            "packages" in data and data["packages"][""]["version"] != version
        ):
            raise ValueError(f"{name}: version differs from {version}")
    for name in LOCKS:
        if any(value != version for _, value in lock_versions((root / name).read_text("utf-8"))):
            raise ValueError(f"{name}: Iris lockfile version differs from {version}")
    if (root / GENERATED).read_text("utf-8").replace("'", '"') != generated(version):
        raise ValueError(f"{GENERATED}: run tools/sync-version.py")
    return version


def replacements(version, root):
    result = {}
    for name in MANIFESTS:
        text = (root / name).read_text("utf-8")
        result[name] = re.sub(
            r'^version = "[^"]+"', f'version = "{version}"', text, count=1, flags=re.M
        )
    for name in JSON_FILES:
        data = json.loads((root / name).read_text("utf-8"))
        data["version"] = version
        if "packages" in data:
            data["packages"][""]["version"] = version
        result[name] = json.dumps(data, ensure_ascii=False, indent=2) + "\n"
    for name in LOCKS:
        text = (root / name).read_text("utf-8")
        for package, old in lock_versions(text):
            text = text.replace(
                f'name = "{package}"\nversion = "{old}"',
                f'name = "{package}"\nversion = "{version}"',
            )
        result[name] = text
    result[GENERATED] = generated(version)
    text = (root / "README.md").read_text("utf-8")
    result["README.md"] = re.sub(
        r"Current source version: \*\*[^*]+\*\*", f"Current source version: **{version}**", text
    )
    return result


def sync(version, root=ROOT):
    validate(version)
    # Parse and prepare every file before changing any; dependency versions remain intact.
    prepared = replacements(version, root)
    changed = []
    for name, text in prepared.items():
        path = root / name
        if not path.exists() or path.read_text("utf-8") != text:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
            changed.append(name)
    check(version, root)
    return changed
